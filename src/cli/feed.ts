import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { MergedData } from '../data/types';
import { renderSvg } from '../render/svg';

/**
 * A personal, agent-readable data feed: the opencode.ai/data idea for one developer.
 *
 *   index.json        merged daily counts per year (labels anonymized unless --labels)
 *   index.md          summary table with links to each year
 *   YYYY.md           one page per year: total, active days, busiest day, monthly table
 *   graph.svg         merged rolling-year heatmap, for READMEs and sites
 *
 * Only counts per day are published: no repo names, titles, hosts or usernames.
 */

export interface FeedOptions {
  title?: string;
  /** Keep real source labels instead of "Source 1, 2, …". */
  labels?: boolean;
  /** Public URL the feed is served from, for the citation line. */
  url?: string;
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

function yearStats(data: MergedData, year: number) {
  const months = new Array<number>(12).fill(0);
  let total = 0;
  let activeDays = 0;
  let busiest: { date: string; count: number } | null = null;
  const days: Record<string, number> = {};
  const cal = data.years.find((y) => y.year === year);
  for (const week of cal?.weeks ?? []) {
    for (const day of week.days) {
      if (!day.date.startsWith(`${year}-`) || !day.known || day.count <= 0) continue;
      days[day.date] = day.count;
      total += day.count;
      activeDays++;
      months[Number(day.date.slice(5, 7)) - 1] += day.count;
      if (!busiest || day.count > busiest.count) busiest = { date: day.date, count: day.count };
    }
  }
  return { total, activeDays, busiest, months, days };
}

export function writeFeed(data: MergedData, outDir: string, options: FeedOptions = {}): string[] {
  mkdirSync(outDir, { recursive: true });
  const updated = data.generatedAt;
  const title = options.title ?? 'Contribution history';
  const sources = data.sources.map((s, i) => ({
    label: options.labels ? s.label : `Source ${i + 1}`,
    type: s.type,
    coverage: s.coverage,
  }));
  const years = data.years
    .map((y) => ({ year: y.year, ...yearStats(data, y.year) }))
    .filter((y) => y.total > 0)
    .sort((a, b) => b.year - a.year);
  const written: string[] = [];
  const write = (name: string, body: string) => {
    writeFileSync(resolve(outDir, name), body);
    written.push(name);
  };
  const cite = options.url ? `Cite: ${title} (${options.url}), updated ${updated.slice(0, 10)}.` : `Updated ${updated.slice(0, 10)}.`;

  write('index.json', `${JSON.stringify({
    title,
    updated,
    generator: 'contribs.sh',
    sources,
    years: years.map(({ year, total, activeDays, busiest, months, days }) => ({ year, total, activeDays, busiest, months, days })),
  }, null, 2)}\n`);

  const all = years.reduce((sum, y) => sum + y.total, 0);
  const index = [
    `# ${title}`,
    '',
    `> ${all.toLocaleString('en-US')} contributions across ${sources.length} source(s), ${years.at(-1)?.year ?? ''}–${years[0]?.year ?? ''}. ${cite}`,
    '',
    '- JSON: [index.json](index.json)',
    '- Heatmap: [graph.svg](graph.svg)',
    '',
    '| Year | Contributions | Active days | Busiest day |',
    '| --- | ---: | ---: | --- |',
    ...years.map((y) => `| [${y.year}](${y.year}.md) | ${y.total.toLocaleString('en-US')} | ${y.activeDays} | ${y.busiest ? `${y.busiest.date} (${y.busiest.count})` : ''} |`),
    '',
    '## Sources',
    '',
    ...sources.map((s) => `- ${s.label} (${s.type}): ${s.coverage.from} to ${s.coverage.to}`),
    '',
    '## Methodology',
    '',
    'Daily contribution counts from each source, summed per day. Days no source covers are not counted.',
    'Only counts are published: no repository names, titles, hosts or usernames. Generated by contribs.sh.',
    '',
  ].join('\n');
  write('index.md', index);

  for (const y of years) {
    write(`${y.year}.md`, [
      `# ${y.year}`,
      '',
      `> ${y.total.toLocaleString('en-US')} contributions on ${y.activeDays} active days${y.busiest ? `; busiest day ${y.busiest.date} (${y.busiest.count})` : ''}. ${cite}`,
      '',
      '| Month | Contributions |',
      '| --- | ---: |',
      ...y.months.map((n, i) => `| ${MONTHS[i]} | ${n.toLocaleString('en-US')} |`),
      '',
      '[All years](index.md) · [JSON](index.json)',
      '',
    ].join('\n'));
  }

  write('graph.svg', renderSvg(data, { preset: 'og', title }));
  return written;
}
